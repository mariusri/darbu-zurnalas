-- Komerciniai pasiūlymai ir jų šablonai (tik administratoriams)
-- Supabase → SQL Editor → New query → įklijuokite → Run. Galima paleisti kelis kartus.

create table if not exists public.offers (
  id uuid primary key default gen_random_uuid(),
  no bigint generated by default as identity (start with 179),   -- tęsia Wantly numeraciją
  object_id uuid references public.objects(id) on delete cascade,
  title text not null default '',
  date date not null default current_date,
  valid_until date,
  show_prices boolean not null default false,   -- false: viena kaina, eilutės „Įskaičiuota“
  vat numeric not null default 21,
  discount numeric not null default 0,          -- €, be PVM
  lines jsonb not null default '[]'::jsonb,     -- [{name, qty, unit, price, desc}], price be PVM
  notes text not null default '',
  total numeric not null default 0,             -- su PVM, sąrašui
  author text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists offers_object on public.offers (object_id, date desc);

create table if not exists public.offer_templates (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  title text not null default '',
  show_prices boolean not null default false,
  lines jsonb not null default '[]'::jsonb,
  notes text not null default '',
  updated_at timestamptz not null default now()
);

alter table public.offers enable row level security;
alter table public.offer_templates enable row level security;
drop policy if exists "offers admin" on public.offers;
drop policy if exists "offer templates admin" on public.offer_templates;
create policy "offers admin" on public.offers for all to authenticated
  using (public.is_admin()) with check (public.is_admin());
create policy "offer templates admin" on public.offer_templates for all to authenticated
  using (public.is_admin()) with check (public.is_admin());
